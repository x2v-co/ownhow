// Site-only public configuration. Read one complete JSON object from stdin;
// never accept paths, HTML, private credentials, or provider API keys.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

export function renderSiteConfiguration(input, html) {
  if (!input || typeof input !== "object" || Array.isArray(input)) throw new Error("Expected a JSON object");
  const rules = {
    measurementId: /^G-[A-Z0-9]{10}$/,
    googleSiteVerification: /^[A-Za-z0-9_-]{1,256}$/,
    bingSiteVerification: /^[A-Fa-f0-9]{32}$/
  };
  for (const name of Object.keys(input)) {
    if (!Object.hasOwn(rules, name)) throw new Error(`Unsupported public field: ${name}`);
  }
  for (const [name, rule] of Object.entries(rules)) {
    const value = input[name] ?? "";
    if (typeof value !== "string" || (value !== "" && !rule.test(value))) {
      throw new Error(`Invalid public field: ${name}`);
    }
  }
  const start = "<!-- ownhow-verification:start -->";
  const end = "<!-- ownhow-verification:end -->";
  if (html.split(start).length !== 2 || html.split(end).length !== 2 || html.indexOf(start) > html.indexOf(end)) {
    throw new Error("Expected one verification marker pair");
  }
  const metas = [];
  if (input.googleSiteVerification) metas.push(`<meta name="google-site-verification" content="${input.googleSiteVerification}">`);
  if (input.bingSiteVerification) metas.push(`<meta name="msvalidate.01" content="${input.bingSiteVerification}">`);
  return {
    config: "/* Public website configuration; generated by scripts/configure-site.js. */\n"
      + `window.ownhowAnalytics = Object.freeze({ measurementId: ${JSON.stringify(input.measurementId ?? "")} });\n`,
    html: html.slice(0, html.indexOf(start)) + start + "\n  "
      + (metas.length ? metas.join("\n  ") + "\n  " : "") + html.slice(html.indexOf(end))
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2) throw new Error("Use stdin JSON only; no file paths or arguments");
  let json = "";
  for await (const chunk of process.stdin) {
    json += chunk;
    if (json.length > 4096) throw new Error("Public configuration too large");
  }
  const site = resolve(dirname(fileURLToPath(import.meta.url)), "../site");
  const rendered = renderSiteConfiguration(JSON.parse(json), await readFile(resolve(site, "index.html"), "utf8"));
  // All values and markup are validated before either source file is written.
  await writeFile(resolve(site, "analytics-config.js"), rendered.config);
  await writeFile(resolve(site, "index.html"), rendered.html);
}
